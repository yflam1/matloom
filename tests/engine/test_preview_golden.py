# Byte stability of the numba/numpy stack is only guaranteed per version pair.
# Each listed pair has been verified to produce the digests below: the dev
# capture env (numpy 2.4.6 + numba 0.65.1) and a fresh py3.10
# requirements-test.txt install (numpy 2.2.6 + numba 0.67.0, what CI's 3.10
# leg resolves today), so the gate executes there instead of skipping.
_RECORDED_VERSIONS = (("2.4.6", "0.65.1"), ("2.2.6", "0.67.0"))

pytestmark = pytest.mark.skipif(
    (np.__version__, numba.__version__) not in _RECORDED_VERSIONS,
    reason=(
        f"golden bytes were recorded on the numpy/numba pairs "
        f"{_RECORDED_VERSIONS}, this env runs numpy {np.__version__} + numba "
        f"{numba.__version__}; the runtime-oracle tests in test_noise.py "
        "remain the version-robust gate"
    ),
)


"""Golden byte gate for ``fixed_light_preview`` at 256 — the committed CI
counterpart of the dev-machine fingerprint harness. Pins sha256(tobytes +
shape + dtype) for the 10 slowest corpus programs of the baseline bench plus 2
Define/Rotate-heavy ones (programs copied verbatim into
``tests/data/golden_programs/``; provenance in
``/tmp/preview_bench/corpus_manifest.json`` at capture time). numpy and numba
are unpinned in requirements-test.txt, so a CI install on a different version
pair may legitimately produce different bytes: the test skips there instead of
flaking (the runtime-oracle tests in ``test_noise.py`` — kernel vs scalar
``__call__`` / legacy numpy loop — are the version-robust exactness gate). When
the version pair moves, re-render the golden set on the new pair and commit the
new digests only after the 0-ulp oracles still pass."""


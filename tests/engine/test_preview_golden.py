def _digest(arr: np.ndarray) -> str:
    h = hashlib.sha256()
    h.update(arr.tobytes())
    h.update(f"{arr.shape}{arr.dtype}".encode())
    return h.hexdigest()


@pytest.mark.parametrize("name,digest", sorted(_GOLDEN_256.items()))
def test_golden_preview_256(name: str, digest: str) -> None:
    material = LayeredMaterial.deserialize((_GOLDEN_DIR / name).read_text())
    arr = fixed_light_preview(material, _SIZE, _SIZE)
    assert arr.dtype == np.uint8
    assert arr.shape == (_SIZE, _SIZE, 3)
    assert _digest(arr) == digest
